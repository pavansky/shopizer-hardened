-- Checkout Idempotency-Key store. One row per (merchant, key).
-- ORDER_ID is null while the checkout is in flight.
CREATE TABLE ORDER_IDEMPOTENCY_KEY (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  MERCHANT_ID INTEGER NOT NULL,
  IDEMPOTENCY_KEY VARCHAR(255) NOT NULL,
  CART_CODE VARCHAR(255) NOT NULL,
  REQUEST_HASH VARCHAR(64) NOT NULL,
  ORDER_ID BIGINT NULL,
  DATE_CREATED DATETIME NOT NULL,
  PRIMARY KEY (ID),
  CONSTRAINT UK_ORDER_IDEMPOTENCY_KEY UNIQUE (MERCHANT_ID, IDEMPOTENCY_KEY)
);

CREATE INDEX IDX_ORDER_IDEMPOTENCY_ORDER ON ORDER_IDEMPOTENCY_KEY (ORDER_ID);
