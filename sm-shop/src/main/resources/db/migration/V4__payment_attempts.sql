-- Write-ahead record of every payment gateway call. A row is committed in
-- INITIATED before the gateway is called, so the reconciler can ask the
-- gateway about a charge whose payment transaction was never stored.
CREATE TABLE PAYMENT_ATTEMPT (
  ID BIGINT NOT NULL AUTO_INCREMENT,
  ORDER_ID BIGINT NOT NULL,
  MERCHANT_ID INTEGER NOT NULL,
  MODULE_CODE VARCHAR(64) NOT NULL,
  ATTEMPT_REF VARCHAR(36) NOT NULL,
  GATEWAY_REF VARCHAR(255) NULL,
  AMOUNT DECIMAL(19,2) NULL,
  CURRENCY VARCHAR(3) NULL,
  STATUS VARCHAR(16) NOT NULL,
  FAILURE_REASON VARCHAR(255) NULL,
  DATE_CREATED DATETIME NOT NULL,
  DATE_UPDATED DATETIME NOT NULL,
  PRIMARY KEY (ID),
  CONSTRAINT UK_PAYMENT_ATTEMPT_REF UNIQUE (ATTEMPT_REF)
);

CREATE INDEX IDX_PAYMENT_ATTEMPT_ORDER ON PAYMENT_ATTEMPT (ORDER_ID);
CREATE INDEX IDX_PAYMENT_ATTEMPT_STATUS ON PAYMENT_ATTEMPT (STATUS, DATE_CREATED);
